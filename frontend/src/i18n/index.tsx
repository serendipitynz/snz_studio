const dictionaries = { en, ja };

function format(template: string, vars?: Vars): string {
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

function readLanguage(): Language {
  if (typeof window === "undefined") {
    return "ja";
  }
  const stored = window.localStorage.getItem(LANGUAGE_KEY);
  return stored === "ja" || stored === "en" ? stored : "ja";
}

interface LanguageValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: MessageKey, vars?: Vars) => string;
}

const LanguageContext = createContext<LanguageValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(readLanguage);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
    }
  }, [lang]);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    if (typeof window !== "undefined") {
      window.localStorage.setItem(LANGUAGE_KEY, next);
    }
  }, []);

  const t = useCallback(
    (key: MessageKey, vars?: Vars) => format(dictionaries[lang][key] ?? en[key] ?? key, vars),
    [lang]
  );

  const value = useMemo<LanguageValue>(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageValue {
  const value = useContext(LanguageContext);
  if (!value) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return value;
}
